// ForegroundUsage resolves a virtual key through the active window's layout.
func ForegroundUsage(vk byte) (byte, bool) {
	if !SupportsKey(vk) && vk != 0x0d { // Enter is used for scheduled login.
		return 0, false
	}
	window := windows.GetForegroundWindow()
	if window == 0 {
		return 0, false
	}
	thread, _, _ := getWindowThread.Call(uintptr(window), 0)
	if thread == 0 {
		return 0, false
	}
	layout, _, _ := getKeyboardLayout.Call(thread)
	const mapVKToScanEx = 4
	scan, _, _ := mapVirtualKeyEx.Call(uintptr(vk), mapVKToScanEx, layout)
	if scan >= uintptr(len(scanUsage)) {
		return 0, false
	}
	return scanUsage[scan], scanUsage[scan] != 0
}
